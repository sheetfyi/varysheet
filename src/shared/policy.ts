/**
 * 一份文案的短指纹（djb2，8 位十六进制）：注册时把当时生效的条款版本记进
 * `users.terms_version`，日后核对用户同意的是哪一版；改文案指纹就会变。
 * 只用于「版本标识」，不做安全用途。
 */
export function policyVersion(content: string): string {
  let hash = 5381;
  for (let index = 0; index < content.length; index += 1) {
    hash = ((hash << 5) + hash + content.charCodeAt(index)) >>> 0;
  }
  return hash.toString(16).padStart(8, '0');
}
